/**
 * Serialized stories — the intrinsic-motivation half of the content bank.
 *
 * The audit's engagement finding (build plan H-E1): disconnected two-sentence
 * fragments about a cat on a chair give a nine-year-old no reason to do one
 * more item. Her *interest* level is years ahead of her *decoding* level, and
 * low-interest-low-level text is the classic struggling-reader trap. Chapters
 * with recurring characters supply the pull that stars only rent — she does the
 * next item because she wants to know what happens.
 *
 * Each series climbs in level across its chapters, so continuing the story is
 * also a gentle difficulty ramp. Chapters are ordinary passages to the engine:
 * the composer, no-repeat rule and scaffold treat them like any other, and the
 * `series`/`chapter` fields exist so the Library (Phase 9) can shelve them as
 * books rather than a heap of fragments.
 *
 * ⚠️ NIKUD REVIEW: Dima proofs vocalization; regenerate the review sheet with
 * `npx vitest run scripts/`.
 */

import type { PassageQuestion, ReadingLevel, SkillCode, VocabTier } from '../types';

export interface Chapter {
  id:         string;
  chapter:    number;
  title:      string;
  level:      ReadingLevel;
  vocabTier:  VocabTier;
  full:       string;
  questions:  Array<Omit<PassageQuestion, 'id' | 'passageId'>>;   // q() fills hintText
}

export interface Series {
  id:        string;
  title:     string;
  blurb:     string;      // shown on the Library shelf
  emoji:     string;
  names:     string[];
  chapters:  Chapter[];
}

