import type { Passage, PassageQuestion, ReadingLevel, VocabTier } from '../types';
import { SERIES } from './series';

export interface PassageSeed {
  passage:   Passage;
  questions: PassageQuestion[];
}

function wc(text: string): number {
  return text.trim().split(/\s+/).filter(Boolean).length;
}

/** Small authoring helper — fills ids and word count so entries stay terse. */
function seed(args: {
  id: string;
  level: ReadingLevel;
  vocabTier: VocabTier;
  full: string;
  genre?: string;
  names?: string[];
  picture?: string;
  // hintText is optional at authoring time — most questions don't need one,
  // and the format falls back to a generic hint.
  questions: Array<Omit<PassageQuestion, 'id' | 'passageId' | 'hintText'> & { hintText?: string | null }>;
}): PassageSeed {
  const passage: Passage = {
    id:               args.id,
    level:            args.level,
    vocabTier:        args.vocabTier,
    wordCount:        wc(args.full),
    textFullNikud:    args.full,
    textPartialNikud: null,  // derived
    textNoNikud:      null,  // derived
    characterNames:   args.names ?? [],
    genre:            args.genre ?? null,
    picture:          args.picture ?? null,
  };
  const questions: PassageQuestion[] = args.questions.map((q, i) => ({
    ...q,
    hintText:  q.hintText ?? null,
    id:        `q_${args.id}_${i + 1}`,
    passageId: args.id,
  }));
  return { passage, questions };
}

